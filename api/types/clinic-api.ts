// Frontend TypeScript interfaces matching the C# DTOs in api/Dtos.
// ASP.NET Core serializes property names as camelCase.
// DateTime is serialized as an ISO 8601 string (e.g. "2026-11-05T14:00:00").

/** M = morning, A = afternoon, E = evening */
export type Session = 'M' | 'A' | 'E';

export type AppointmentStatus = 'BOOKED' | 'CHECKED_IN' | 'DONE' | 'CANCELLED';

/** GET /api/clinic?date=yyyy-MM-dd&deptId=1  (ClinicListItemDto) */
export interface ClinicListItem {
  appointmentId: number;
  patientId: number;
  deptName: string;
  doctorName: string;
  session: Session;
  seqNo: number;
  chartNo: string;
  patientName: string;
  status: AppointmentStatus;
}

/** GET /api/patients/{id}/vitals?days=14&page=&pageSize=  returns PagedResult<VitalSign>  (VitalSignDto) */
export interface VitalSign {
  vitalId: number;
  measuredAt: string;
  systolicBP: number | null;
  diastolicBP: number | null;
  heartRate: number | null;
  bloodSugar: number | null;
  bodyWeight: number | null;
  note: string | null;
}

/** PATCH /api/appointments/{id}/checkin  (CheckInResultDto) */
export interface CheckInResult {
  appointmentId: number;
  status: AppointmentStatus;
}

/** Error body for 400 / 404 / 409 / 500 (RFC 9110 ProblemDetails) */
export interface ProblemDetails {
  type?: string;
  title?: string;
  status?: number;
  detail?: string;
  traceId?: string;
  /** Present on 400 validation errors: field name to messages */
  errors?: Record<string, string[]>;
}

/** POST /api/patients/{id}/vitals, PUT /api/vitals/{vitalId}  (VitalSignInput)
 *  measuredAt: local time "yyyy-MM-ddTHH:mm:ss" without time zone. */
export interface VitalSignInput {
  measuredAt: string;
  systolicBP: number | null;
  diastolicBP: number | null;
  heartRate: number | null;
  bloodSugar: number | null;
  bodyWeight: number | null;
  note: string | null;
}

/** POST /api/auth/login  (LoginRequest) */
export interface LoginRequest {
  username: string;
  password: string;
}

/** POST /api/auth/login response (ASP.NET Core bearer token handler).
 *  Send accessToken as "Authorization: Bearer {accessToken}". */
export interface AccessTokenResponse {
  tokenType: 'Bearer';
  accessToken: string;
  /** Seconds until accessToken expires. */
  expiresIn: number;
  refreshToken: string;
}

/** GET /api/auth/me  (CurrentUserDto) */
export interface CurrentUser {
  username: string;
  displayName: string;
}

// ---------- Paging ----------

/** Paged list response. Query params: page (from 1), pageSize (1-100, default 20).
 *  When page is beyond the last page, items is empty and totalCount is still accurate. */
export interface PagedResult<T> {
  items: T[];
  totalCount: number;
  page: number;
  pageSize: number;
}

/** PATCH /api/{patients|doctors|departments}/{id}/status */
export interface StatusInput {
  isActive: boolean;
}

// ---------- Departments ----------

/** GET /api/departments?includeInactive=&page=&pageSize=  (DepartmentDto) */
export interface Department {
  deptId: number;
  deptCode: string;
  deptName: string;
  isActive: boolean;
  /** Optimistic concurrency token (Base64). Send it back unchanged on PUT. */
  rowVersion: string;
}

/** POST /api/departments, PUT /api/departments/{id}  (DepartmentInput) */
export interface DepartmentInput {
  /** 2-10 uppercase letters or digits */
  deptCode: string;
  deptName: string;
  /** Required on PUT */
  rowVersion?: string;
}

// ---------- Doctors ----------

/** GET /api/doctors?deptId=&includeInactive=&page=&pageSize=  (DoctorDto) */
export interface Doctor {
  doctorId: number;
  deptId: number;
  deptCode: string;
  deptName: string;
  doctorName: string;
  title: string;
  isActive: boolean;
  rowVersion: string;
}

/** POST /api/doctors, PUT /api/doctors/{id}  (DoctorInput) */
export interface DoctorInput {
  deptId: number;
  doctorName: string;
  title: string;
  rowVersion?: string;
}

// ---------- Patients ----------

export type Gender = 'M' | 'F';

/** GET /api/patients?keyword=&includeInactive=&page=&pageSize=  (PatientListItemDto)
 *  phone is masked, e.g. "0900-***-001". */
export interface PatientListItem {
  patientId: number;
  chartNo: string;
  patientName: string;
  gender: Gender;
  birthDate: string;
  phone: string | null;
  isActive: boolean;
}

/** GET /api/patients/{id}  (PatientDto) */
export interface Patient {
  patientId: number;
  chartNo: string;
  patientName: string;
  gender: Gender;
  birthDate: string;
  phone: string | null;
  address: string | null;
  emergencyContact: string | null;
  emergencyPhone: string | null;
  isActive: boolean;
  createdAt: string;
  updatedAt: string | null;
  rowVersion: string;
}

/** POST /api/patients, PUT /api/patients/{id}  (PatientInput). chartNo is generated by the server. */
export interface PatientInput {
  patientName: string;
  gender: Gender;
  /** yyyy-MM-dd */
  birthDate: string;
  phone: string | null;
  address: string | null;
  emergencyContact: string | null;
  emergencyPhone: string | null;
  rowVersion?: string;
}
